/**
 * document-preservation.test.ts — generation headers on LF, CRLF, mixed and BOM documents (0.14.0).
 *
 *   DP1  LF documents: byte-identical to the released 0.13.0 header functions (no behavior change)
 *   DP2  CRLF documents: the header and its blank line are CRLF; nothing else changes; inverse holds
 *   DP3  mixed documents: only the insertion point's own line ending is used; no whole-file rewrite
 *   DP4  UTF-8 BOM: kept first, the H1 after it is recognised, the header goes below it; none added
 *   DP5  final newline (present / absent) preserved
 *   DP6  stamp-docs on a core.autocrlf=true checkout: no false "changed", idempotent, no state churn,
 *        a line-ending flip keeps the date, a real body change updates it
 *   DP7  legacy records written by the RELEASED 0.13.0 stamp-docs (LF and CRLF, H1 and top
 *        placement) are recognised from the other checkout: no new date, no rewrite of state
 *   DP8  a BOM document 0.13.0 stamped above its H1 is corrected once, keeping its date
 *
 * Run with: node --no-warnings scripts/document-preservation.test.ts
 */

import { createHash } from "crypto";
import { execFileSync, spawnSync } from "child_process";
import { mkdtempSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { extractRelease, helper } from "./fixtures/inspected.ts";
import { commitOrigin, crlf, employeeClone, eolCounts, gitEol, lfClone } from "./fixtures/line-endings.ts";
import { write } from "./fixtures/knowledge-fixtures.ts";
import { bodyHashMatches, findHeader, insertHeader, placement, stripHeader } from "./doc-header.ts";

let failures = 0;
function check(name: string, cond: boolean, detail = ""): void {
  if (cond) console.log(`PASS  ${name}`);
  else { failures++; console.log(`FAIL  ${name}${detail ? `  — ${detail}` : ""}`); }
}

const root = realpathSync(mkdtempSync(join(tmpdir(), "inspector-docs-")));
const REL_0130 = "3ef4cd1771b57fd969ff2b78e95f33931a9fcea5";
const H = { version: "0.14.0", knowledgeCommit: "a1b2c3d", updated: "2026-11-25" };
const BOM = "﻿";
const OLD_DATE = "2026-01-02";
const WORK = "task/inspect-refresh";

const CORPUS: Record<string, string> = {
  "h1 + blank": "# Title\n\nBody line.\n\n## Section\n\nMore.\n",
  "h1, no blank": "# Title\nBody line.\n",
  "leading blank lines": "\n\n# Title\n\nBody.\n",
  "no h1": "Intro text.\n\n## Section\n",
  "no final newline": "# Title\n\nBody without newline",
  "h1 only, no newline": "# Title",
  "empty": "",
  "old header present": "# Title\n\nGenerated by ono-project-inspector 0.12.0 · knowledge at unknown · updated 2026-01-01\n\nBody.\n",
};

const released = join(root, "inspector-0.13.0");
extractRelease(REL_0130, ["scripts", "skills", ".claude-plugin"], released);
const old = await import(join(released, "scripts", "doc-header.ts"));
const oldStamp = (dir: string, ...rels: string[]) => spawnSync(process.execPath, ["--no-warnings", join(released, "scripts", "inspection-state.ts"), "stamp-docs", dir, ...rels], { encoding: "utf-8" });
const stamp = (dir: string, ...rels: string[]) => helper(dir, "inspection-state.ts", "stamp-docs", dir, ...rels);
const action = (r: { json: any }, i = 0) => r.json?.results?.[i]?.action;
const state = (dir: string) => JSON.parse(readFileSync(join(dir, ".ono", "state.json"), "utf-8"));
const stateStat = (dir: string) => { const p = join(dir, ".ono", "state.json"); return `${statSync(p).mtimeMs}:${readFileSync(p, "utf-8")}`; };
/** Give a stamped document (file header + state record) an old date, to prove a date is kept. */
function ageRecord(dir: string, rel: string): void {
  const s = state(dir);
  s.documents[rel].updated = OLD_DATE;
  writeFileSync(join(dir, ".ono", "state.json"), JSON.stringify(s, null, 2) + "\n");
  const p = join(dir, rel);
  writeFileSync(p, readFileSync(p, "utf-8").replace(/updated \d{4}-\d{2}-\d{2}/, `updated ${OLD_DATE}`));
}
const headerDate = (dir: string, rel: string) => findHeader(readFileSync(join(dir, rel), "utf-8"))?.updated;

try {
  // --- DP1 ------------------------------------------------------------------------------------------
  for (const [name, body] of Object.entries(CORPUS)) {
    const same = insertHeader(body, H) === old.insertHeader(body, H) && stripHeader(body) === old.stripHeader(body) &&
      placement(body) === old.placement(body) && JSON.stringify(findHeader(body)) === JSON.stringify(old.findHeader(body));
    check(`DP1 LF "${name}": identical to released 0.13.0`, same);
  }

  // --- DP2 ------------------------------------------------------------------------------------------
  for (const [name, body] of Object.entries(CORPUS)) {
    if (!body.includes("\n")) continue;
    const c = crlf(body);
    const out = insertHeader(c, H);
    check(`DP2 CRLF "${name}": the stamped document is uniformly CRLF`, !/(?<!\r)\n/.test(out), JSON.stringify(out.slice(0, 80)));
    check(`DP2 CRLF "${name}": it is exactly the LF result with CRLF endings`, out === crlf(insertHeader(body, H)));
    check(`DP2 CRLF "${name}": stripping returns the same body as on LF (CRLF-encoded)`, stripHeader(out) === crlf(stripHeader(insertHeader(body, H))));
  }

  // --- DP3 ------------------------------------------------------------------------------------------
  {
    const mixed = "# Title\r\n\r\nCRLF paragraph.\r\nLF line one.\nLF line two.\n\n## Section\r\nEnd.\n";
    const out = insertHeader(mixed, H);
    const expected = "# Title\r\n\r\nGenerated by ono-project-inspector 0.14.0 · knowledge at a1b2c3d · updated 2026-11-25\r\n\r\nCRLF paragraph.\r\nLF line one.\nLF line two.\n\n## Section\r\nEnd.\n";
    check("DP3 mixed: the header uses the H1 line's CRLF; every other byte is unchanged", out === expected, JSON.stringify(out));
    const lfH1 = "# Title\n\nBody.\r\nMore.\r\n";
    check("DP3 mixed with an LF H1: the header uses LF; the CRLF lines stay CRLF", insertHeader(lfH1, H) === "# Title\n\nGenerated by ono-project-inspector 0.14.0 · knowledge at a1b2c3d · updated 2026-11-25\n\nBody.\r\nMore.\r\n");
    check("DP3 mixed: stripping restores the original exactly", stripHeader(out) === mixed);
  }

  // --- DP4 ------------------------------------------------------------------------------------------
  {
    const bom = BOM + "# CLAUDE.md\r\n\r\nBody.\r\n";
    check("DP4 BOM: the H1 after a BOM is recognised", placement(bom) === "after-h1");
    const out = insertHeader(bom, H);
    check("DP4 BOM: kept as the first character, header below the H1, CRLF kept", out === BOM + "# CLAUDE.md\r\n\r\nGenerated by ono-project-inspector 0.14.0 · knowledge at a1b2c3d · updated 2026-11-25\r\n\r\nBody.\r\n", JSON.stringify(out));
    check("DP4 BOM: stripping restores the document byte for byte", stripHeader(out) === bom);
    check("DP4 BOM: findHeader reads it", findHeader(out)?.updated === "2026-11-25");
    const noH1 = BOM + "Intro.\n";
    const top = insertHeader(noH1, H);
    check("DP4 BOM, no H1: the BOM stays first, the header follows it", top.startsWith(BOM + "Generated by") && stripHeader(top) === noH1 && findHeader(top) !== null);
    check("DP4 no BOM is ever introduced", Object.values(CORPUS).every((b) => !insertHeader(b, H).includes(BOM) && !insertHeader(crlf(b), H).includes(BOM)));
    // A 0.13.0 output (header placed above the BOM H1) strips back to the BOM document.
    const legacy = old.insertHeader(bom, H);
    check("DP4 0.13.0 put the header above a BOM H1 (the confirmed defect)", legacy.startsWith("Generated by") && legacy.includes("\n" + BOM + "#"));
    check("DP4 ...and that legacy output strips back to the original BOM document", stripHeader(legacy) === bom);
  }

  // --- DP5 ------------------------------------------------------------------------------------------
  {
    const a = insertHeader("# T\r\n\r\nNo newline at end", H);
    const b = insertHeader("# T\r\n\r\nNewline at end\r\n", H);
    check("DP5 no final newline stays absent; a final CRLF stays CRLF", !a.endsWith("\n") && b.endsWith("end\r\n"));
    check("DP5 an H1 that ends the file gains only the separator it needs", insertHeader("# T", H) === "# T\n\nGenerated by ono-project-inspector 0.14.0 · knowledge at a1b2c3d · updated 2026-11-25");
  }

  // --- body hash recognition (unit) -----------------------------------------------------------------
  {
    const sha = (t: string) => createHash("sha256").update(t, "utf-8").digest("hex");
    const body = "# Title\n\nBody.\n";
    check("DP  canonical, raw, uniform-CRLF and 0.13.0-CRLF-stamp encodings are all recognised",
      bodyHashMatches(sha(body), crlf(body)) && bodyHashMatches(sha(crlf(body)), body) && bodyHashMatches(sha("# Title\r\n\nBody.\r\n"), body) && bodyHashMatches(sha(crlf(body)), crlf(body)));
    check("DP  a content change is never recognised, in any encoding", !bodyHashMatches(sha(body), "# Title\n\nBody!\n") && !bodyHashMatches(sha(crlf(body)), "# Title\r\n\r\nBody!\r\n") && !bodyHashMatches(sha("# Title\r\n\nBody.\r\n"), "# Title\n\nBody!\n"));
  }

  // --- DP6 ------------------------------------------------------------------------------------------
  const origin = join(root, "origin");
  write(origin, "AUDIT.md", "# AUDIT.md\n\n## Audit Topics\n\n| # | Status | Topic | Priority | File | Notes |\n|---|---|---|---|---|---|\n| 1 | Approved | Architecture | High | audits/architecture/architecture-audit.md | Approved 2026-11-01 |\n");
  write(origin, "CLAUDE.md", "# CLAUDE.md\n\n## Project Overview\n\nDemo.\n");
  write(origin, "audits/architecture/architecture-audit.md", "Architecture notes without an H1.\n\n## Findings\n\nNone.\n");
  commitOrigin(origin, "dev");
  {
    const d = employeeClone(origin, join(root, "dp6"), "AUDIT.md", WORK).dir;
    const before = readFileSync(join(d, "CLAUDE.md"));
    const r = stamp(d, "CLAUDE.md");
    check("DP6 an unchanged committed document on a CRLF checkout is skipped (0.13.0: falsely 'stamped')", action(r) === "skipped-no-baseline" && Buffer.compare(before, readFileSync(join(d, "CLAUDE.md"))) === 0, r.stdout);
    writeFileSync(join(d, "AUDIT.md"), readFileSync(join(d, "AUDIT.md"), "utf-8") + "\r\nRefreshed.\r\n");
    const s1 = stamp(d, "AUDIT.md");
    const c1 = eolCounts(join(d, "AUDIT.md"));
    check("DP6 a changed CRLF document is stamped and stays uniformly CRLF", action(s1) === "stamped" && c1.bareLf === 0 && c1.crlf > 0, JSON.stringify(c1));
    const st1 = stateStat(d);
    const s2 = stamp(d, "AUDIT.md");
    check("DP6 the second run changes nothing — no document write, no state.json write (0.13.0: 'restored')", action(s2) === "unchanged" && stateStat(d) === st1);
    const lfBody = stripHeader(readFileSync(join(d, "AUDIT.md"), "utf-8")).replace(/\r\n/g, "\n");
    check("DP6 the record is canonical (SHA-256 of the LF body)", state(d).documents["AUDIT.md"].bodySha256 === createHash("sha256").update(lfBody, "utf-8").digest("hex"));
    ageRecord(d, "AUDIT.md");
    writeFileSync(join(d, "AUDIT.md"), readFileSync(join(d, "AUDIT.md"), "utf-8").replace(/\r\n/g, "\n"));
    const st2 = stateStat(d);
    const s3 = stamp(d, "AUDIT.md");
    check("DP6 a line-ending-only flip keeps the header date and writes no state", action(s3) === "unchanged" && headerDate(d, "AUDIT.md") === OLD_DATE && stateStat(d) === st2, s3.stdout);
    writeFileSync(join(d, "AUDIT.md"), readFileSync(join(d, "AUDIT.md"), "utf-8").replace("Refreshed.", "Refreshed again."));
    const s4 = stamp(d, "AUDIT.md");
    check("DP6 a genuine body change is stamped with a new date", action(s4) === "stamped" && headerDate(d, "AUDIT.md") !== OLD_DATE);
  }

  // --- DP7 ------------------------------------------------------------------------------------------
  {
    // (a) 0.13.0 stamps on an LF checkout; the same commit is read from a CRLF checkout.
    const lfWork = join(root, "dp7-lf");
    lfClone(origin, lfWork);
    gitEol(lfWork, "false", "switch", "-q", "-c", WORK);
    writeFileSync(join(lfWork, "AUDIT.md"), readFileSync(join(lfWork, "AUDIT.md"), "utf-8") + "\nRefreshed.\n");
    writeFileSync(join(lfWork, "audits/architecture/architecture-audit.md"), "Architecture notes without an H1, revised.\n\n## Findings\n\nNone.\n");
    const o1 = oldStamp(lfWork, "AUDIT.md", "audits/architecture/architecture-audit.md");
    check("DP7a released 0.13.0 stamped both documents on LF", o1.status === 0 && /"stamped"/.test(o1.stdout), o1.stdout + o1.stderr);
    ageRecord(lfWork, "AUDIT.md");
    ageRecord(lfWork, "audits/architecture/architecture-audit.md");
    gitEol(lfWork, "false", "add", "-A");
    gitEol(lfWork, "false", "commit", "-q", "-m", "stamped by 0.13.0 on LF");
    const asCrlf = employeeClone(lfWork, join(root, "dp7-lf-as-crlf"), "AUDIT.md", "task/read").dir;
    const st = stateStat(asCrlf);
    const r = stamp(asCrlf, "AUDIT.md", "audits/architecture/architecture-audit.md");
    check("DP7a an LF-era 0.13.0 record is recognised on a CRLF checkout: unchanged, old date, no writes",
      action(r, 0) === "unchanged" && action(r, 1) === "unchanged" && headerDate(asCrlf, "AUDIT.md") === OLD_DATE && stateStat(asCrlf) === st && gitEol(asCrlf, "true", "status", "--porcelain") === "", r.stdout);

    // (b) 0.13.0 stamps on a CRLF checkout (H1 placement, and top placement); read from an LF checkout.
    const crWork = employeeClone(origin, join(root, "dp7-crlf"), "AUDIT.md", WORK).dir;
    writeFileSync(join(crWork, "AUDIT.md"), readFileSync(join(crWork, "AUDIT.md"), "utf-8") + "\r\nRefreshed.\r\n");
    writeFileSync(join(crWork, "audits/architecture/architecture-audit.md"), crlf("Architecture notes without an H1, revised.\n\n## Findings\n\nNone.\n"));
    const o2 = oldStamp(crWork, "AUDIT.md", "audits/architecture/architecture-audit.md");
    check("DP7b released 0.13.0 stamped both documents on CRLF", o2.status === 0 && /"stamped"/.test(o2.stdout), o2.stdout + o2.stderr);
    check("DP7b ...leaving bare-LF lines in the CRLF AUDIT.md (the 0.13.0 mixed-ending write)", eolCounts(join(crWork, "AUDIT.md")).bareLf > 0);
    ageRecord(crWork, "AUDIT.md");
    ageRecord(crWork, "audits/architecture/architecture-audit.md");
    const recorded = state(crWork).documents;
    const RELS = ["AUDIT.md", "audits/architecture/architecture-audit.md"];
    const as013 = Object.fromEntries(RELS.map((rel) => [rel, readFileSync(join(crWork, rel))]));
    const bareBefore = eolCounts(join(crWork, "AUDIT.md")).bareLf;
    // Same checkout, 0.14.0: recognised; the header lines 0.13.0 wrote with LF get the document's CRLF, date kept.
    const r2 = stamp(crWork, "AUDIT.md", "audits/architecture/architecture-audit.md");
    check("DP7b on the same CRLF checkout 0.14.0 recognises both records and keeps the old date",
      action(r2, 0) === "restored" && action(r2, 1) === "restored" && headerDate(crWork, "AUDIT.md") === OLD_DATE && headerDate(crWork, RELS[1]) === OLD_DATE, r2.stdout);
    // The blank line 0.13.0 wrote with LF below the H1 is now body content: it is preserved, not rewritten.
    check("DP7b ...the header lines become CRLF; no new bare LF is written", eolCounts(join(crWork, "AUDIT.md")).bareLf === bareBefore - 1 && eolCounts(join(crWork, RELS[1])).bareLf === 0, JSON.stringify(eolCounts(join(crWork, "AUDIT.md"))));
    check("DP7b ...and a further run is unchanged", action(stamp(crWork, ...RELS), 0) === "unchanged");
    check("DP7b ...the records written by 0.13.0 are kept or re-encoded, never re-dated", Object.values(state(crWork).documents).every((x: any) => x.updated === OLD_DATE));
    // Now the 0.13.0 records (as 0.13.0 left them) read from an LF checkout of the committed content.
    const lfRead = join(root, "dp7-crlf-as-lf");
    for (const rel of RELS) writeFileSync(join(crWork, rel), as013[rel]);
    writeFileSync(join(crWork, ".ono", "state.json"), JSON.stringify({ ...state(crWork), documents: recorded }, null, 2) + "\n");
    gitEol(crWork, "true", "add", "-A");
    gitEol(crWork, "true", "commit", "-q", "-m", "stamped by 0.13.0 on CRLF");
    lfClone(crWork, lfRead);
    gitEol(lfRead, "false", "switch", "-q", "-c", "task/read");
    const st3 = stateStat(lfRead);
    const r3 = stamp(lfRead, "AUDIT.md", "audits/architecture/architecture-audit.md");
    check("DP7b a Windows-era 0.13.0 record (H1 placement) is recognised on an LF checkout: unchanged, old date",
      action(r3, 0) === "unchanged" && headerDate(lfRead, "AUDIT.md") === OLD_DATE, r3.stdout);
    check("DP7b a Windows-era 0.13.0 record (top placement) is recognised on an LF checkout",
      action(r3, 1) === "unchanged" && headerDate(lfRead, "audits/architecture/architecture-audit.md") === OLD_DATE, r3.stdout);
    check("DP7b ...without rewriting state.json to migrate the hashes", stateStat(lfRead) === st3);
    writeFileSync(join(lfRead, "AUDIT.md"), readFileSync(join(lfRead, "AUDIT.md"), "utf-8").replace("Refreshed.", "Changed."));
    const r4 = stamp(lfRead, "AUDIT.md");
    check("DP7b a genuine change after a legacy record is stamped with a new date", action(r4) === "stamped" && headerDate(lfRead, "AUDIT.md") !== OLD_DATE);
  }

  // --- DP8 ------------------------------------------------------------------------------------------
  {
    const d = join(root, "dp8");
    write(d, "CLAUDE.md", BOM + "# CLAUDE.md\n\n## Overview\n\nDemo.\n");
    write(d, "AUDIT.md", "# AUDIT.md\n");
    commitOrigin(d, WORK);
    writeFileSync(join(d, "CLAUDE.md"), BOM + "# CLAUDE.md\n\n## Overview\n\nDemo, refreshed.\n");
    const o = oldStamp(d, "CLAUDE.md");
    check("DP8 released 0.13.0 put the header above the BOM H1", o.status === 0 && readFileSync(join(d, "CLAUDE.md"), "utf-8").startsWith("Generated by"), readFileSync(join(d, "CLAUDE.md"), "utf-8").slice(0, 60));
    ageRecord(d, "CLAUDE.md");
    const r = stamp(d, "CLAUDE.md");
    const text = readFileSync(join(d, "CLAUDE.md"), "utf-8");
    check("DP8 0.14.0 moves it below the H1 once ('restored'), keeping the BOM first and the date", action(r) === "restored" && text.startsWith(BOM + "# CLAUDE.md\n\nGenerated by") && headerDate(d, "CLAUDE.md") === OLD_DATE, JSON.stringify(text.slice(0, 120)));
    check("DP8 ...and is idempotent afterwards", action(stamp(d, "CLAUDE.md")) === "unchanged");
  }
} finally {
  rmSync(root, { recursive: true, force: true });
}

console.log(failures === 0 ? "\nALL TESTS PASSED" : `\n${failures} TEST(S) FAILED`);
process.exit(failures === 0 ? 0 : 1);
