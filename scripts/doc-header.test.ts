/**
 * doc-header.test.ts
 *
 * Generation headers on Inspector documents (0.13.0): scripts/doc-header.ts and
 * `inspection-state.ts stamp-docs`.
 *
 *   H1  format: installed version, 7-character knowledge commit, UTC date
 *   H2  fixed location: under the H1, or the first line when there is no H1
 *   H3  idempotent: a repeat stamp writes nothing (documents and state.json untouched)
 *   H4  exactly one header; a header-like line in developer body text is never touched
 *   H5  an unchanged body keeps its date; a changed body gets today's date
 *   H6  developer-authored content is preserved
 *   H7  the knowledge commit comes from the recorded baseline; `unknown` when absent
 *   H8  no backfill: an unchanged document an older version wrote is left as it is
 *   H9  only Inspector-generated documents are stamped; all-or-nothing on errors
 *   H10 refused on a protected branch, nothing written
 *   H11 every document-writing workflow keeps manifest fingerprints valid, and header
 *       churn never makes knowledge look stale
 *   H12 parsers, evidence gate and refresh guard are unaffected by the header
 *   H13 nested Project Root and non-ASCII document paths
 *   H14 a removed or misplaced header is restored with its original date
 *   H15 workflow contract: stamp before emit; approval and re-check never stamp
 *
 * No external test framework. Run with:
 *   node --no-warnings scripts/doc-header.test.ts
 */

import { createHash } from "crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { dirname, join } from "path";
import { findHeader, headerLine, HEADER_RE, insertHeader, parseHeader, placement, stripHeader, todayUtc } from "./doc-header.ts";
import { g, helper, inspectedRepo, PLUGIN } from "./fixtures/inspected.ts";

let failures = 0;
function check(name: string, cond: boolean, detail = ""): void {
  if (cond) console.log(`PASS  ${name}`);
  else { failures++; console.log(`FAIL  ${name}${detail ? `  — ${detail}` : ""}`); }
}

const VERSION = JSON.parse(readFileSync(join(PLUGIN, ".claude-plugin", "plugin.json"), "utf-8")).version as string;
const DOCS = ["docs/project/overview.md", "docs/project/components.md", "docs/project/patterns.md", "docs/project/integrations.md", "docs/project/capabilities.md"];
const root = realpathSync(mkdtempSync(join(tmpdir(), "inspector-header-")));
const read = (dir: string, rel: string) => readFileSync(join(dir, rel), "utf-8");
const put = (dir: string, rel: string, body: string) => { mkdirSync(dirname(join(dir, rel)), { recursive: true }); writeFileSync(join(dir, rel), body); };
const append = (dir: string, rel: string, extra: string) => writeFileSync(join(dir, rel), read(dir, rel) + extra);
const stamp = (dir: string, ...rels: string[]) => helper(dir, "inspection-state.ts", "stamp-docs", dir, ...rels);
const state = (dir: string) => JSON.parse(read(dir, ".ono/state.json"));
const sha = (t: string) => createHash("sha256").update(t, "utf-8").digest("hex");
const commit = (dir: string, msg: string) => { g(dir, "add", "-A"); g(dir, "commit", "-q", "-m", msg); };
const today = todayUtc();
const hdrOf = (dir: string, rel: string) => findHeader(read(dir, rel));

try {
  // --- H1 / H2: format and location (pure) ----------------------------------------------------------
  const line = headerLine({ version: "0.13.0", knowledgeCommit: "a1b2c3d", updated: "2026-11-24" });
  check("H1 the line is exactly the approved format", line === "Generated by ono-project-inspector 0.13.0 · knowledge at a1b2c3d · updated 2026-11-24");
  check("H1 it parses back", JSON.stringify(parseHeader(line)) === JSON.stringify({ version: "0.13.0", knowledgeCommit: "a1b2c3d", updated: "2026-11-24" }));
  check("H1 an 8-character or uppercase commit is not a header (exactly 7 hex)", !HEADER_RE.test(line.replace("a1b2c3d", "a1b2c3d4")) && !HEADER_RE.test(line.replace("a1b2c3d", "A1B2C3D")));
  check("H1 `unknown` is the only non-commit value", HEADER_RE.test(line.replace("a1b2c3d", "unknown")) && !HEADER_RE.test(line.replace("a1b2c3d", "HEAD")));
  const withH1 = "# Title\n\n> audience\n\n## Section\ntext\n";
  check("H2 under the H1, separated by one blank line", insertHeader(withH1, parseHeader(line)!) === `# Title\n\n${line}\n\n> audience\n\n## Section\ntext\n`);
  check("H2 leading blank lines before the H1 are kept", placement("\n\n# T\nx\n") === "after-h1" && insertHeader("\n\n# T\nx\n", parseHeader(line)!) === `\n\n# T\n\n${line}\nx\n`);
  const noH1 = "Some notes\n## Section\n";
  check("H2 no H1: the header becomes the first line, nothing removed", placement(noH1) === "top" && insertHeader(noH1, parseHeader(line)!) === `${line}\n\n${noH1}`);
  check("H2 strip is the inverse of insert", stripHeader(insertHeader(withH1, parseHeader(line)!)) === withH1 && stripHeader(insertHeader(noH1, parseHeader(line)!)) === noH1);

  // --- an inspected repository written by 0.11.3 (no headers) ------------------------------------------------
  const repo = join(root, "repo");
  const kh = inspectedRepo(repo);
  const short = kh.slice(0, 7);

  // --- H8: no backfill ----------------------------------------------------------------------------------------
  const untouched = read(repo, "CLAUDE.md");
  const nb = stamp(repo, "CLAUDE.md", ...DOCS);
  check("H8 unchanged documents from an older version are skipped, not backfilled", nb.code === 0 && nb.json?.results?.every((r: any) => r.action === "skipped-no-baseline"), JSON.stringify(nb.json?.results?.map((r: any) => r.action)));
  check("H8 ...and left byte-identical", read(repo, "CLAUDE.md") === untouched && hdrOf(repo, "CLAUDE.md") === null);
  check("H8 no state write when nothing changed", g(repo, "status", "--porcelain") === "");
  check("H8 missing headers never make knowledge stale", helper(repo, "inspection-state.ts", "detect", repo).json?.knowledge?.status === "COMPLETE");

  // --- H5 / H7: a regenerated document is stamped -----------------------------------------------------------------
  append(repo, "CLAUDE.md", "\n<!-- regenerated -->\n");
  const r1 = stamp(repo, "CLAUDE.md");
  const h1 = hdrOf(repo, "CLAUDE.md");
  check("H5 a changed (regenerated) document is stamped today", r1.code === 0 && r1.json?.results?.[0]?.action === "stamped" && h1?.updated === today, JSON.stringify(r1.json));
  check("H1 version comes from the installed plugin.json", h1?.version === VERSION);
  check("H7 CLAUDE.md names the project-analysis knowledgeHead (7 characters)", h1?.knowledgeCommit === short && state(repo).stages["project-analysis"].knowledgeHead.startsWith(short));
  check("H7 the record is stored in state.documents", state(repo).documents?.["CLAUDE.md"]?.knowledgeCommit === short && typeof state(repo).documents?.["CLAUDE.md"]?.bodySha256 === "string");

  // --- H3: idempotent ---------------------------------------------------------------------------------------------
  const stamped = read(repo, "CLAUDE.md");
  const stateBefore = read(repo, ".ono/state.json");
  const r2 = stamp(repo, "CLAUDE.md");
  check("H3 a repeat stamp reports unchanged", r2.json?.results?.[0]?.action === "unchanged");
  check("H3 ...and writes neither the document nor state.json", read(repo, "CLAUDE.md") === stamped && read(repo, ".ono/state.json") === stateBefore);

  // --- H5: dates ------------------------------------------------------------------------------------------------------
  // Pretend the header was written on an earlier day (record and file agree).
  const old = state(repo);
  old.documents["CLAUDE.md"].updated = "2026-01-02";
  writeFileSync(join(repo, ".ono/state.json"), JSON.stringify(old, null, 2));
  writeFileSync(join(repo, "CLAUDE.md"), read(repo, "CLAUDE.md").replace(`updated ${today}`, "updated 2026-01-02"));
  check("H5 an unchanged body keeps its earlier date", stamp(repo, "CLAUDE.md").json?.results?.[0]?.action === "unchanged" && hdrOf(repo, "CLAUDE.md")?.updated === "2026-01-02");
  append(repo, "CLAUDE.md", "one more line\n");
  check("H5 a body change moves the date to today", stamp(repo, "CLAUDE.md").json?.results?.[0]?.action === "stamped" && hdrOf(repo, "CLAUDE.md")?.updated === today);

  // --- H4 / H6: one header, developer content preserved ------------------------------------------------------------------
  const dev = read(repo, "CLAUDE.md");
  const devBody = stripHeader(dev);
  const dup = dev.replace(/^(Generated by .*)$/m, "$1\n$1\n$1");
  writeFileSync(join(repo, "CLAUDE.md"), dup + `\n## Developer notes\nGenerated by ono-project-inspector 9.9.9 · knowledge at abcdef1 · updated 2020-01-01\n`);
  stamp(repo, "CLAUDE.md");
  const after = read(repo, "CLAUDE.md");
  const top = after.split("\n## ")[0];
  check("H4 exactly one header in the top region", (top.match(/^Generated by ono-project-inspector /gm) ?? []).length === 1, top.slice(0, 300));
  check("H4 a header-like line in developer body text is left untouched", after.includes("## Developer notes\nGenerated by ono-project-inspector 9.9.9 · knowledge at abcdef1 · updated 2020-01-01\n"));
  check("H6 every original body line survives, in order", stripHeader(after).startsWith(devBody.replace(/\n$/, "")), "");

  // --- H7: per-document baselines ---------------------------------------------------------------------------------------------
  for (const d of DOCS) append(repo, d, "\n<!-- regenerated -->\n");
  stamp(repo, ...DOCS);
  check("H7 docs/project/* name the project-docs knowledgeHead", DOCS.every((d) => hdrOf(repo, d)?.knowledgeCommit === state(repo).stages["project-docs"].knowledgeHead.slice(0, 7)));
  commit(repo, "stamped docs");
  put(repo, "audits/architecture/architecture-audit.md", read(repo, "audits/architecture/architecture-audit.md") + "\nmore\n");
  stamp(repo, "audits/architecture/architecture-audit.md");
  check("H7 an audit file names the HEAD it was (re)written at", hdrOf(repo, "audits/architecture/architecture-audit.md")?.knowledgeCommit === g(repo, "rev-parse", "HEAD").slice(0, 7));
  const nok = join(root, "no-knowledge-head");
  inspectedRepo(nok);
  const s0 = state(nok); delete s0.stages["project-analysis"].knowledgeHead;
  writeFileSync(join(nok, ".ono/state.json"), JSON.stringify(s0, null, 2));
  append(nok, "CLAUDE.md", "x\n");
  stamp(nok, "CLAUDE.md");
  check("H7 no recorded baseline -> `knowledge at unknown`, never a guessed commit", hdrOf(nok, "CLAUDE.md")?.knowledgeCommit === "unknown");

  // --- H9: only Inspector documents, all-or-nothing ------------------------------------------------------------------------------
  put(repo, "docs/project/team-notes.md", "# Team notes\n");
  append(repo, "AUDIT.md", "\n");
  const auditBefore = read(repo, "AUDIT.md");
  for (const bad of ["README.md", "src/index.ts", "docs/project/team-notes.md", "../outside.md", ".ono/state.json"]) {
    const r = stamp(repo, "AUDIT.md", bad);
    check(`H9 ${bad} is refused (exit 1)`, r.code === 1 && r.json?.results?.some((x: any) => x.path.endsWith(bad.replace("../", "")) && x.action === "error"), JSON.stringify(r.json));
  }
  check("H9 a refused batch writes nothing, not even the valid document", read(repo, "AUDIT.md") === auditBefore && read(repo, "docs/project/team-notes.md") === "# Team notes\n");
  check("H9 a missing document is an error", stamp(repo, "docs/project/overview.md", "audits/missing/missing-audit.md").code === 1);

  // --- H10: protected branch -------------------------------------------------------------------------------------------------------------
  const prot = join(root, "protected");
  inspectedRepo(prot);
  append(prot, "CLAUDE.md", "x\n");
  const pBefore = read(prot, "CLAUDE.md");
  g(prot, "branch", "-m", "main");
  const pr = stamp(prot, "CLAUDE.md");
  check("H10 stamp-docs on main refuses with exit 5", pr.code === 5, pr.stdout + pr.stderr);
  check("H10 nothing was written", read(prot, "CLAUDE.md") === pBefore && state(prot).documents === undefined);

  // --- H11 / H12: workflow order keeps fingerprints valid ---------------------------------------------------------------------------------------
  const wf = join(root, "workflow");
  inspectedRepo(wf);
  const fingerprintsMatch = (dir: string) => {
    const m = JSON.parse(read(dir, ".ono/repo-knowledge.json"));
    return Object.entries(m.fingerprint.artifacts as Record<string, string | null>).every(([rel, h]) => (h === null ? !existsSync(join(dir, rel)) : h === sha(read(dir, rel))));
  };
  const emit = (dir: string) => helper(dir, "repo-knowledge.ts", "emit", dir).code === 0 && helper(dir, "repo-knowledge.ts", "validate", dir).code === 0;
  // Refresh of project-analysis: snapshot -> skill writes -> guard -> evidence -> record -> STAMP -> emit
  check("H12 refresh guard snapshot", helper(wf, "knowledge-refresh-guard.ts", "snapshot", wf).code === 0);
  append(wf, "CLAUDE.md", "\n<!-- refreshed -->\n");
  append(wf, "AUDIT.md", "\n");
  const guard = helper(wf, "knowledge-refresh-guard.ts", "verify", wf);
  check("H12 preservation guard passes", guard.code === 0, guard.stdout + guard.stderr);
  check("H12 evidence gate (surfaces)", helper(wf, "knowledge-evidence.ts", "verify", wf, "surfaces").code === 0);
  check("H12 record-knowledge", helper(wf, "inspection-state.ts", "record-knowledge", wf, "project-analysis").code === 0);
  // verify consumed the snapshot; take a fresh one so the stamp happens between snapshot and verify.
  helper(wf, "knowledge-refresh-guard.ts", "snapshot", wf);
  check("H11 analysis: stamp", stamp(wf, "CLAUDE.md", "AUDIT.md").code === 0);
  check("H12 the evidence gate still passes on stamped documents", helper(wf, "knowledge-evidence.ts", "verify", wf, "all").code === 0);
  check("H12 the preservation guard passes across a stamp (snapshot before, verify after)", helper(wf, "knowledge-refresh-guard.ts", "verify", wf).code === 0);
  check("H11 analysis: emit after stamp -> every fingerprint matches the file on disk", emit(wf) && fingerprintsMatch(wf));
  const m1 = JSON.parse(read(wf, ".ono/repo-knowledge.json"));
  check("H12 the manifest still indexes topics, capabilities and surfaces", m1.auditTopics?.length === 1 && m1.capabilities?.length > 0 && m1.coverage?.surfaces === "populated", JSON.stringify(m1.coverage));
  // project-docs
  for (const d of DOCS) append(wf, d, "\n<!-- refreshed -->\n");
  helper(wf, "inspection-state.ts", "record-knowledge", wf, "project-docs");
  check("H11 docs: stamp then emit -> fingerprints match", stamp(wf, ...DOCS).code === 0 && emit(wf) && fingerprintsMatch(wf));
  // audit-breakdown of a new topic: AUDIT.md row + new audit file -> stamp -> emit
  writeFileSync(join(wf, "AUDIT.md"), read(wf, "AUDIT.md").replace(/(\| 1 \| Approved[^\n]*\n)/, "$1| 2 | Draft | Networking | Medium | audits/networking/networking-audit.md | new |\n"));
  put(wf, "audits/networking/networking-audit.md", "# Networking Audit\n\nStatus: Draft\n\n## Findings\n");
  check("H11 breakdown: stamp audit + AUDIT.md then emit -> fingerprints match", stamp(wf, "audits/networking/networking-audit.md", "AUDIT.md").code === 0 && emit(wf) && fingerprintsMatch(wf));
  // approval: only the row changes; no stamp; emit
  const auditHeader = hdrOf(wf, "AUDIT.md");
  writeFileSync(join(wf, "AUDIT.md"), read(wf, "AUDIT.md").replace("| 2 | Draft | Networking", "| 2 | Approved | Networking"));
  check("H11 approval: no stamp, emit -> fingerprints match", emit(wf) && fingerprintsMatch(wf));
  check("H11 approval did not change the header", JSON.stringify(hdrOf(wf, "AUDIT.md")) === JSON.stringify(auditHeader));
  // audit-sync: managed blocks in CLAUDE.md change -> stamp CLAUDE.md -> emit
  writeFileSync(join(wf, "CLAUDE.md"), read(wf, "CLAUDE.md").replace(/(<!-- audit-sync:caution-areas:start -->\n)[\s\S]*?(<!-- audit-sync:caution-areas:end -->)/, "$1- 🔴 HIGH — synced finding\n$2"));
  const cs = stamp(wf, "CLAUDE.md");
  check("H11 audit-sync: CLAUDE.md stamped, knowledge commit unchanged (still project-analysis)", cs.code === 0 && hdrOf(wf, "CLAUDE.md")?.knowledgeCommit === state(wf).stages["project-analysis"].knowledgeHead.slice(0, 7));
  check("H11 audit-sync: emit -> fingerprints match", emit(wf) && fingerprintsMatch(wf));
  commit(wf, "all workflows");
  helper(wf, "inspection-state.ts", "sync", wf);
  commit(wf, "sync");
  check("H11 header churn in every Inspector document never makes knowledge stale", helper(wf, "inspection-state.ts", "detect", wf).json?.knowledge?.status === "COMPLETE");
  check("H12 AUDIT.md topic parsing unaffected (2 topics)", state(wf).counts?.total === 2, JSON.stringify(state(wf).counts));

  // --- H13: nested Project Root + non-ASCII paths ------------------------------------------------------------------------------------------------------
  const umbrella = join(root, "nested umbrella");
  const project = join(umbrella, "פרויקט");
  const tmpTree = join(root, "tree-only");
  inspectedRepo(tmpTree);
  rmSync(join(tmpTree, ".git"), { recursive: true, force: true });
  mkdirSync(umbrella);
  g(umbrella, "init", "-q", "-b", "chore/project-inspection");
  renameSync(tmpTree, project);
  commit(umbrella, "nested");
  const nb2 = stamp(project, "CLAUDE.md");
  check("H13 nested: committed-version comparison works below the Git Root (no backfill)", nb2.json?.results?.[0]?.action === "skipped-no-baseline", JSON.stringify(nb2.json));
  put(project, "audits/ניהול/ניהול-audit.md", "# ניהול Audit\n\nStatus: Draft\n");
  const heb = stamp(project, "audits/ניהול/ניהול-audit.md");
  check("H13 a non-ASCII audit path is stamped", heb.code === 0 && hdrOf(project, "audits/ניהול/ניהול-audit.md")?.updated === today, JSON.stringify(heb.json));

  // --- H14: restore -------------------------------------------------------------------------------------------------------------------------------------------
  const keep = hdrOf(repo, "CLAUDE.md");
  writeFileSync(join(repo, "CLAUDE.md"), stripHeader(read(repo, "CLAUDE.md")));
  const rs = stamp(repo, "CLAUDE.md");
  check("H14 a removed header is restored with its original date (body unchanged)", rs.json?.results?.[0]?.action === "restored" && JSON.stringify(hdrOf(repo, "CLAUDE.md")) === JSON.stringify(keep), JSON.stringify(rs.json));

  // --- H15: workflow contract ---------------------------------------------------------------------------------------------------------------------------------
  const hook = (n: string) => readFileSync(join(PLUGIN, "hooks", `${n}.md`), "utf-8");
  const pos = (text: string, s: string) => text.indexOf(s);
  for (const [n, files] of [["after-project-analysis", "CLAUDE.md AUDIT.md"], ["after-project-docs", DOCS.join(" ")], ["after-audit-sync", "CLAUDE.md"]] as const) {
    const t = hook(n);
    const st = pos(t, `stamp-docs "<TARGET_ROOT>" ${files}`);
    check(`H15 ${n}: stamps exactly its documents`, st > 0);
    check(`H15 ${n}: stamp runs before the manifest emit`, st > 0 && st < pos(t, "**Refresh the repository-knowledge manifest.**"));
    if (n !== "after-audit-sync") check(`H15 ${n}: stamp runs after record-knowledge`, pos(t, "record-knowledge") > 0 && pos(t, "record-knowledge") < st);
  }
  const bd = hook("after-audit-breakdown");
  check("H15 after-audit-breakdown: stamps the audit file and AUDIT.md, then emits", pos(bd, 'stamp-docs "<TARGET_ROOT>" audits/<slug>/<slug>-audit.md AUDIT.md') > 0 && pos(bd, "stamp-docs") < pos(bd, "(`emit`)"));
  const ap = hook("after-audit-approve");
  check("H15 after-audit-approve never runs stamp-docs", !/node [^`]*stamp-docs/.test(ap) && /Do \*\*not\*\* run `stamp-docs` here/.test(ap));
  for (const s of ["project-analysis", "project-docs", "audit-breakdown", "audit-sync"]) {
    check(`H15 skills/${s} never writes the header itself`, /\*\*Generation header\.\*\* Never write, edit or copy/.test(readFileSync(join(PLUGIN, "skills", s, "SKILL.md"), "utf-8")));
  }
} finally {
  rmSync(root, { recursive: true, force: true });
}

console.log(failures === 0 ? "\nALL TESTS PASSED" : `\n${failures} TEST(S) FAILED`);
process.exit(failures === 0 ? 0 : 1);
